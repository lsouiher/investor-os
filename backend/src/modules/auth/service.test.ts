/**
 * The account language travels from the database to every auth response: the web client
 * switches its interface to `user.locale` after sign-in, on any device. Only prisma is mocked,
 * so the real repository writes the language at registration.
 *
 * Value: protects=register/login/getProfile/updateProfile return the stored locale, and
 * register writes it to the new user row; fails_when=locale is dropped from toProfile, the
 * AuthResponse user, or createUserWithTenant's insert; why_new=main.test.ts mocks the auth
 * service, so nothing checked what it returns; seam=none
 * Generated by /ship test coverage audit (pass 2).
 */
process.env.JWT_SECRET = 'test-secret';

const mockUserCreate = jest.fn();
const mockTenantCreate = jest.fn();
const mockFindUnique = jest.fn();
const mockFindFirst = jest.fn();
const mockUserUpdate = jest.fn();
jest.mock('../../shared/db.js', () => ({
  prisma: {
    $transaction: (fn: (tx: unknown) => unknown) =>
      fn({
        tenant: { create: (...args: unknown[]) => mockTenantCreate(...args) },
        user: { create: (...args: unknown[]) => mockUserCreate(...args) },
      }),
    user: {
      findUnique: (...args: unknown[]) => mockFindUnique(...args),
      findFirst: (...args: unknown[]) => mockFindFirst(...args),
      update: (...args: unknown[]) => mockUserUpdate(...args),
    },
  },
}));
// bcrypt at 12 rounds is slow and not what is under test
jest.mock('bcrypt', () => ({
  hash: jest.fn().mockResolvedValue('hashed'),
  compare: jest.fn().mockResolvedValue(true),
}));
jest.mock('../../shared/email.js', () => ({ sendPasswordResetEmail: jest.fn() }));

import { getProfile, login, register, updateProfile } from './service';

const createdAt = new Date('2026-09-01T12:00:00.000Z');
const storedUser = (locale: string) => ({
  id: 7,
  publicId: 'pub_7',
  email: 'a@b.co',
  role: 'investor',
  locale,
  passwordHash: 'hashed',
  deletedAt: null,
  createdAt,
});

describe('the account language in auth responses', () => {
  beforeEach(() => {
    mockTenantCreate.mockReset().mockResolvedValue({ id: 3 });
    // The row comes back with whatever language the repository wrote
    mockUserCreate.mockReset().mockImplementation(async ({ data }: { data: { locale: string } }) => storedUser(data.locale));
    mockFindUnique.mockReset();
    mockFindFirst.mockReset();
    mockUserUpdate.mockReset();
  });

  it('writes the registration language to the new account and returns it', async () => {
    mockFindUnique.mockResolvedValue(null);

    const result = await register('a@b.co', 'password123', null, 'fr');

    expect(mockUserCreate).toHaveBeenCalledWith({ data: expect.objectContaining({ locale: 'fr' }) });
    expect(result.user).toEqual({ id: 'pub_7', email: 'a@b.co', role: 'investor', locale: 'fr' });
    expect(typeof result.token).toBe('string');
  });

  it('starts an account in English when no language is given', async () => {
    mockFindUnique.mockResolvedValue(null);

    const result = await register('a@b.co', 'password123');

    expect(mockUserCreate).toHaveBeenCalledWith({ data: expect.objectContaining({ locale: 'en' }) });
    expect(result.user.locale).toBe('en');
  });

  it('returns the stored language on sign-in, not the language of the page', async () => {
    mockFindUnique.mockResolvedValue(storedUser('fr'));
    mockUserUpdate.mockResolvedValue({});

    const result = await login('a@b.co', 'password123');

    expect(result.user.locale).toBe('fr');
  });

  it('returns the stored language in the profile', async () => {
    mockFindFirst.mockResolvedValue(storedUser('fr'));

    await expect(getProfile(7)).resolves.toEqual({
      id: 'pub_7',
      email: 'a@b.co',
      role: 'investor',
      locale: 'fr',
      createdAt: '2026-09-01T12:00:00.000Z',
    });
  });

  it('saves a new language and returns the profile as saved', async () => {
    mockUserUpdate.mockImplementation(async ({ data }: { data: { locale: string } }) => storedUser(data.locale));

    const profile = await updateProfile(7, { locale: 'en' });

    expect(mockUserUpdate).toHaveBeenCalledWith({ where: { id: 7 }, data: { locale: 'en' } });
    expect(profile.locale).toBe('en');
  });
});
