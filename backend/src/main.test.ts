/**
 * The assembled app, through HTTP: the order of the global middleware in main.ts is the
 * contract here. The request's language must be resolved before express.json() can refuse a
 * body, so that refusal reaches the error handler with req.locale set.
 *
 * Value: protects=a malformed or oversized body is answered 400/413 in the language of the
 * request; fails_when=resolveLocale moves after express.json() in main.ts, or the parser
 * errors stop mapping to 4xx; why_new=error-handler.test.ts calls errorHandler with a hand-set
 * req.locale and never runs the real middleware chain; seam=none
 * Value: protects=a new account starts in the page's language unless the body names one, and
 * PUT /auth/me saves only en|fr, refusing in the account's language; fails_when=the register
 * route drops `?? req.locale` or PUT /me skips validateLocale; why_new=validation.test.ts
 * covers the validators only, no route test existed; seam=none
 * Generated by /ship test coverage audit (pass 1).
 */
process.env.JWT_SECRET = 'test-secret';

import jwt from 'jsonwebtoken';
import request from 'supertest';

// No database, model or queue is reached: the auth service is mocked and authenticate reads
// the account through the mocked prisma below
const mockFindUser = jest.fn();
jest.mock('./shared/db.js', () => ({ prisma: { user: { findFirst: (...args: unknown[]) => mockFindUser(...args) } } }));
const mockRegister = jest.fn();
const mockUpdateProfile = jest.fn();
jest.mock('./modules/auth/service.js', () => ({
  register: (...args: unknown[]) => mockRegister(...args),
  updateProfile: (...args: unknown[]) => mockUpdateProfile(...args),
}));
jest.mock('./shared/logger.js', () => ({
  logger: { info: jest.fn(), warn: jest.fn(), error: jest.fn(), debug: jest.fn() },
}));

// Required, not imported: auth.ts reads JWT_SECRET when it loads, so it must load after the line above
const app = (require('./main') as typeof import('./main')).default;

describe('body refusals through the assembled app', () => {
  it('answers a malformed JSON body with 400 in French for a French page', async () => {
    const res = await request(app)
      .post('/api/v1/auth/login')
      .set('Accept-Language', 'fr-CA,fr;q=0.9')
      .set('Content-Type', 'application/json')
      .send('{"email": broken');

    expect(res.status).toBe(400);
    expect(res.body).toEqual({
      error: { code: 'VALIDATION_ERROR', message: 'Le corps de la requête n’est pas un JSON valide.', details: [] },
    });
  });

  it('answers an oversized body with 413 in French for a French page', async () => {
    const res = await request(app)
      .post('/api/v1/auth/login')
      .set('Accept-Language', 'fr')
      .set('Content-Type', 'application/json')
      .send(JSON.stringify({ email: 'a@b.co', password: 'x'.repeat(60 * 1024) }));

    expect(res.status).toBe(413);
    expect(res.body.error).toEqual({
      code: 'VALIDATION_ERROR',
      message: 'Le corps de la requête est trop volumineux.',
      details: [],
    });
  });

  it('keeps English for a page that announces no supported language', async () => {
    const res = await request(app)
      .post('/api/v1/auth/login')
      .set('Accept-Language', 'es')
      .set('Content-Type', 'application/json')
      .send('{nope');

    expect(res.status).toBe(400);
    expect(res.body.error.message).toBe('The request body is not valid JSON.');
  });

  it('answers a validation error before sign-in in the language of the page', async () => {
    const res = await request(app)
      .post('/api/v1/auth/forgot-password')
      .set('Accept-Language', 'fr')
      .send({ email: 'not-an-email' });

    expect(res.status).toBe(400);
    expect(res.body.error).toEqual({
      code: 'VALIDATION_ERROR',
      message: 'Format de courriel non valide.',
      details: [{ field: 'email', message: 'Doit être une adresse courriel valide.' }],
    });
  });
});

describe('the account language through the auth routes', () => {
  beforeEach(() => {
    mockRegister.mockReset().mockResolvedValue({ user: { id: 'u1' }, token: 't' });
    mockUpdateProfile.mockReset().mockResolvedValue({ id: 'u1', locale: 'fr' });
    mockFindUser.mockReset();
  });

  it('registers the account in the language of the page when the body names none', async () => {
    const res = await request(app)
      .post('/api/v1/auth/register')
      .set('Accept-Language', 'fr-CA')
      .send({ email: 'a@b.co', password: 'password123' });

    expect(res.status).toBe(201);
    expect(mockRegister).toHaveBeenCalledWith('a@b.co', 'password123', null, 'fr');
  });

  it('lets the language named in the body win over the page', async () => {
    await request(app)
      .post('/api/v1/auth/register')
      .set('Accept-Language', 'fr')
      .send({ email: 'a@b.co', password: 'password123', locale: 'en' });

    expect(mockRegister).toHaveBeenCalledWith('a@b.co', 'password123', null, 'en');
  });

  describe('PUT /auth/me', () => {
    const bearer = () => `Bearer ${jwt.sign({ sub: 'pub_7', email: 'a@b.co', role: 'investor' }, 'test-secret')}`;

    beforeEach(() => {
      mockFindUser.mockResolvedValue({
        id: 7, publicId: 'pub_7', tenantId: 3, email: 'a@b.co', role: 'investor', locale: 'fr', tokenInvalidatedAt: null,
      });
    });

    it('saves a supported language to the account', async () => {
      const res = await request(app).put('/api/v1/auth/me').set('Authorization', bearer()).send({ locale: 'fr' });

      expect(res.status).toBe(200);
      expect(mockUpdateProfile).toHaveBeenCalledWith(7, { locale: 'fr' });
    });

    it('refuses anything else, in the account language whatever the page says', async () => {
      const res = await request(app)
        .put('/api/v1/auth/me')
        .set('Authorization', bearer())
        .set('Accept-Language', 'en')
        .send({ locale: 'fr-CA' });

      expect(res.status).toBe(400);
      expect(res.body.error).toMatchObject({ code: 'VALIDATION_ERROR', message: 'Langue non valide.' });
      expect(mockUpdateProfile).not.toHaveBeenCalled();
    });

    it('requires a signed-in account', async () => {
      const res = await request(app).put('/api/v1/auth/me').set('Accept-Language', 'fr').send({ locale: 'fr' });

      expect(res.status).toBe(401);
      expect(res.body.error.message).toBe('Authentification requise.');
      expect(mockUpdateProfile).not.toHaveBeenCalled();
    });
  });
});
